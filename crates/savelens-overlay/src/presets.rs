//! Trainer presets ("templates") stored per game in
//! `<SaveLens data dir>/overlay_presets.json`.
//!
//! The file lives next to the store database — never in a game directory —
//! and is written atomically (temporary file in the same data directory +
//! `rename`).

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{anyhow, bail, Context, Result};
use savelens_core::ScalarValue;
use serde::{Deserialize, Serialize};

/// File name inside the data directory.
pub const PRESETS_FILE: &str = "overlay_presets.json";

/// Name of the built-in "max gold" preset.
pub const MAX_GOLD: &str = "Max gold";

/// Value written by the built-in "Max gold" preset (fits every signed and
/// unsigned 32-bit field and most 24-bit ones).
pub const MAX_GOLD_VALUE: i128 = 999_999;

/// Aliases recognised as currency by the built-in preset.
const GOLD_WORDS: &[&str] = &[
    "gold", "oro", "money", "dinero", "coin", "coins", "cash", "credits", "gil", "rupees", "souls", "zeny", "geld",
];

/// One variable of a preset.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PresetEntry {
    pub alias: String,
    /// Value as typed by the user (parsed with [`ScalarValue::parse`]).
    pub value: String,
    /// Freeze the variable (re-applied on every save) or only set it once.
    pub freeze: bool,
}

impl PresetEntry {
    /// Parsed value.
    pub fn scalar(&self) -> Result<ScalarValue> {
        ScalarValue::parse(&self.value).map_err(|e| anyhow!("preset value for {}: {e}", self.alias))
    }
}

/// A named trainer template.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Preset {
    pub name: String,
    pub entries: Vec<PresetEntry>,
    /// Generated by the overlay (not stored in the file).
    #[serde(skip)]
    pub builtin: bool,
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
struct GamePresets {
    /// Game name at the time of saving (for humans reading the file).
    #[serde(default)]
    name: String,
    #[serde(default)]
    presets: Vec<Preset>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
struct PresetFile {
    version: u32,
    /// Keyed by store game id.
    #[serde(default)]
    games: BTreeMap<String, GamePresets>,
}

impl Default for PresetFile {
    fn default() -> Self {
        PresetFile {
            version: 1,
            games: BTreeMap::new(),
        }
    }
}

/// Preset storage backed by `<data dir>/overlay_presets.json`.
#[derive(Debug, Clone)]
pub struct PresetStore {
    path: PathBuf,
    data: PresetFile,
    /// The file on disk could not be parsed; it is moved aside on the next save.
    corrupt: bool,
}

/// True when `alias` names a currency.
pub fn is_currency_alias(alias: &str) -> bool {
    let lower = alias.to_lowercase();
    lower
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
        .any(|w| GOLD_WORDS.contains(&w))
}

/// Built-in presets generated from the current cheat table:
/// "Max gold" freezes every currency-like alias at [`MAX_GOLD_VALUE`].
pub fn builtin_presets(aliases: &[(String, Option<ScalarValue>)]) -> Vec<Preset> {
    let entries: Vec<PresetEntry> = aliases
        .iter()
        .filter(|(a, _)| is_currency_alias(a))
        .map(|(alias, current)| PresetEntry {
            alias: alias.clone(),
            value: match current {
                Some(ScalarValue::Float(_)) => ScalarValue::Float(MAX_GOLD_VALUE as f64).to_string(),
                _ => ScalarValue::Int(MAX_GOLD_VALUE).to_string(),
            },
            freeze: true,
        })
        .collect();
    if entries.is_empty() {
        return Vec::new();
    }
    vec![Preset {
        name: MAX_GOLD.to_string(),
        entries,
        builtin: true,
    }]
}

impl PresetStore {
    /// Path of the presets file for a data directory.
    pub fn path_in(data_dir: &Path) -> PathBuf {
        data_dir.join(PRESETS_FILE)
    }

    /// Loads the presets of `data_dir`. A missing file means "no presets".
    /// A corrupt file yields an error *and* a usable empty store (returned
    /// through [`PresetStore::load_lenient`]).
    pub fn load(data_dir: &Path) -> Result<PresetStore> {
        let path = Self::path_in(data_dir);
        let data = match fs::read_to_string(&path) {
            Ok(text) => serde_json::from_str::<PresetFile>(&text).with_context(|| format!("{} is not valid", path.display()))?,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => PresetFile::default(),
            Err(e) => return Err(anyhow!("cannot read {}: {e}", path.display())),
        };
        Ok(PresetStore {
            path,
            data,
            corrupt: false,
        })
    }

    /// Like [`PresetStore::load`] but never fails: on error an empty store is
    /// returned with the error message. The unreadable file is preserved as
    /// `overlay_presets.json.corrupt` (in the data dir) on the next save.
    pub fn load_lenient(data_dir: &Path) -> (PresetStore, Option<String>) {
        match Self::load(data_dir) {
            Ok(s) => (s, None),
            Err(e) => (
                PresetStore {
                    path: Self::path_in(data_dir),
                    data: PresetFile::default(),
                    corrupt: true,
                },
                Some(format!("{e:#}")),
            ),
        }
    }

    /// File backing this store.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Custom presets of a game.
    pub fn presets(&self, game: i64) -> &[Preset] {
        self.data
            .games
            .get(&game.to_string())
            .map(|g| g.presets.as_slice())
            .unwrap_or(&[])
    }

    /// Adds or replaces (same name, case-insensitive) a preset and saves.
    pub fn upsert(&mut self, game: i64, game_name: &str, preset: Preset) -> Result<()> {
        let name = preset.name.trim().to_string();
        if name.is_empty() {
            bail!("preset name cannot be empty");
        }
        if preset.entries.is_empty() {
            bail!("preset `{name}` has no variables");
        }
        for e in &preset.entries {
            e.scalar()?;
        }
        let slot = self.data.games.entry(game.to_string()).or_default();
        slot.name = game_name.to_string();
        let preset = Preset {
            name: name.clone(),
            builtin: false,
            ..preset
        };
        match slot.presets.iter_mut().find(|p| p.name.eq_ignore_ascii_case(&name)) {
            Some(existing) => *existing = preset,
            None => slot.presets.push(preset),
        }
        self.save()
    }

    /// Deletes a preset and saves.
    pub fn remove(&mut self, game: i64, name: &str) -> Result<()> {
        let key = game.to_string();
        let Some(slot) = self.data.games.get_mut(&key) else {
            bail!("no preset named `{name}`");
        };
        let before = slot.presets.len();
        slot.presets.retain(|p| !p.name.eq_ignore_ascii_case(name));
        if slot.presets.len() == before {
            bail!("no preset named `{name}`");
        }
        if slot.presets.is_empty() {
            self.data.games.remove(&key);
        }
        self.save()
    }

    /// Writes the file atomically (temporary file in the data dir + rename).
    pub fn save(&mut self) -> Result<()> {
        let dir = self
            .path
            .parent()
            .ok_or_else(|| anyhow!("{} has no parent directory", self.path.display()))?;
        fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
        if self.corrupt && self.path.exists() {
            let aside = self.path.with_extension("json.corrupt");
            fs::rename(&self.path, &aside)
                .with_context(|| format!("cannot move the unreadable {} aside", self.path.display()))?;
        }
        self.corrupt = false;
        let text = serde_json::to_string_pretty(&self.data)?;
        let tmp = dir.join(format!(".{PRESETS_FILE}.{}.tmp", std::process::id()));
        fs::write(&tmp, text.as_bytes()).with_context(|| format!("cannot write {}", tmp.display()))?;
        if let Err(e) = fs::rename(&tmp, &self.path) {
            let _ = fs::remove_file(&tmp);
            return Err(anyhow!("cannot replace {}: {e}", self.path.display()));
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn currency_aliases() {
        assert!(is_currency_alias("Oro"));
        assert!(is_currency_alias("Gold"));
        assert!(is_currency_alias("player gold"));
        assert!(is_currency_alias("Coins_P1"));
        assert!(!is_currency_alias("Vida"));
        assert!(!is_currency_alias("Golden Axe kills"));
    }

    #[test]
    fn builtin_max_gold_keeps_float_type() {
        let p = builtin_presets(&[
            ("Oro".into(), Some(ScalarValue::Float(12.0))),
            ("Vida".into(), Some(ScalarValue::Int(3))),
            ("Gold".into(), None),
        ]);
        assert_eq!(p.len(), 1);
        assert!(p[0].builtin);
        assert_eq!(p[0].entries.len(), 2);
        assert_eq!(p[0].entries[0].scalar().unwrap(), ScalarValue::Float(999_999.0));
        assert_eq!(p[0].entries[1].scalar().unwrap(), ScalarValue::Int(999_999));
        assert!(builtin_presets(&[("Vida".into(), None)]).is_empty());
    }

    #[test]
    fn roundtrip_replace_remove_and_corrupt_file() {
        let dir = tempfile::tempdir().unwrap();
        let mut s = PresetStore::load(dir.path()).unwrap();
        assert!(s.presets(1).is_empty());
        let preset = Preset {
            name: "Speedrun".into(),
            entries: vec![PresetEntry {
                alias: "Vida".into(),
                value: "100".into(),
                freeze: true,
            }],
            builtin: false,
        };
        s.upsert(1, "RPG", preset.clone()).unwrap();
        let mut renamed = preset.clone();
        renamed.name = "speedrun".into();
        renamed.entries[0].value = "250".into();
        s.upsert(1, "RPG", renamed).unwrap();
        let loaded = PresetStore::load(dir.path()).unwrap();
        assert_eq!(loaded.presets(1).len(), 1);
        assert_eq!(loaded.presets(1)[0].entries[0].value, "250");
        assert!(loaded.presets(2).is_empty());

        let mut bad = preset.clone();
        bad.entries[0].value = "lots".into();
        assert!(s.upsert(1, "RPG", bad).is_err());
        s.remove(1, "SPEEDRUN").unwrap();
        assert!(s.remove(1, "SPEEDRUN").is_err());
        assert!(PresetStore::load(dir.path()).unwrap().presets(1).is_empty());

        fs::write(s.path(), b"{ not json").unwrap();
        assert!(PresetStore::load(dir.path()).is_err());
        let (mut lenient, err) = PresetStore::load_lenient(dir.path());
        assert!(err.is_some());
        lenient.upsert(3, "Other", preset).unwrap();
        assert!(dir.path().join("overlay_presets.json.corrupt").exists());
        assert_eq!(PresetStore::load(dir.path()).unwrap().presets(3).len(), 1);
    }
}
